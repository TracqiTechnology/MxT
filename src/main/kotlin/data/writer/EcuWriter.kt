package data.writer

import data.parser.a2l.EcuEntry
import java.io.File
import java.nio.charset.Charset

/**
 * Generates ME7Logger-compatible .ecu and .cfg files from parsed A2L data.
 */
object EcuWriter {

    private val LATIN1 = Charset.forName("ISO-8859-1")

    /**
     * Write ME7Logger-compatible .ecu characteristics file.
     */
    fun writeEcuFile(
        entries: List<EcuEntry>,
        outputFile: File,
        partNumber: String = "1K0907115S",
        swNumber: String = "0261S02469",
        engineId: String = "2.0L R4 TFSI"
    ) {
        outputFile.bufferedWriter(LATIN1).use { w ->
            w.write(";\n")
            w.write("; ECU characteristics for logging with ME7Logger\n")
            w.write(";\n")
            w.write("; Generated by MxT A2L→ECU Generator\n")
            w.write(";\n")
            w.write("; Part number: $partNumber\n")
            w.write("; SW number:   $swNumber\n")
            w.write("; Engine:      $engineId\n")
            w.write(";\n")
            w.write("; NOTE: RAM addresses are SW-version specific.\n")
            w.write("; Other SW versions will have DIFFERENT addresses.\n")
            w.write(";\n\n")

            w.write("[Version]\n")
            w.write("Version           = 1.10\n\n")

            w.write("[Communication]\n")
            w.write("Connect      = SLOW-0x01    ; 5-baud init at address 0x01\n")
            w.write("Communicate  = HM0          ; Headerless mode\n")
            w.write("LogSpeed     = 56000        ; baud rate\n\n")

            w.write("[Identification]\n")
            w.write("HWNumber          = {$partNumber}\n")
            w.write("SWNumber          = {$swNumber}\n")
            w.write("PartNumber        = {$partNumber}\n")
            w.write("SWVersion         = {0001}\n")
            w.write("EngineId          = {$engineId}\n\n")

            w.write("[Measurements]\n")
            w.write("; Conversion: Normal: phys = Factor * raw - Offset\n")
            w.write(";             Inverse: phys = Factor / (raw - Offset)\n")
            w.write(";\n")

            for (e in entries) {
                val aliasStr = if (e.alias.isNotEmpty()) "{${e.alias}}" else "{}"
                val unitStr = if (e.unit.isNotEmpty()) "{${e.unit}}" else "{}"
                val commentStr = if (e.comment.isNotEmpty()) "{${e.comment}}" else "{}"
                val factorStr = formatFactor(e.factor)
                val offsetStr = formatFactor(e.offset)

                w.write(
                    "${e.name.padEnd(16)}, ${aliasStr.padEnd(36)}, " +
                        "0x${String.format("%06X", e.address)}, ${e.size.toString().padStart(2)}, " +
                        "0x${String.format("%04X", e.bitmask)},  ${unitStr.padEnd(10)}, " +
                        "${e.signed}, ${e.inverse}, " +
                        "${factorStr.padStart(14)}, ${offsetStr.padStart(7)}, " +
                        "$commentStr\n"
                )
            }
        }
    }

    /**
     * Write ME7Logger .cfg log configuration file.
     *
     * @param variables list of (name, aliasComment, descComment) triples
     */
    fun writeCfgFile(
        outputFile: File,
        ecuFilename: String,
        variables: List<Triple<String, String, String>>,
        samplesPerSecond: Int = 20,
        description: String = ""
    ) {
        outputFile.bufferedWriter(LATIN1).use { w ->
            w.write(";\n")
            w.write("; $description\n")
            w.write("; Generated by MxT A2L→ECU Generator\n")
            w.write(";\n\n")

            w.write("[Configuration]\n")
            w.write("ECUCharacteristics = $ecuFilename\n")
            w.write("SamplesPerSecond   = $samplesPerSecond\n\n")

            w.write("[LogVariables]\n")
            w.write(";Name            [Alias]                             [; Comment]\n")

            for ((name, aliasComment, descComment) in variables) {
                if (name.isEmpty()) {
                    w.write("\n")
                    continue
                }
                val sb = StringBuilder(name.padEnd(17))
                if (aliasComment.isNotEmpty()) {
                    sb.append(";{$aliasComment}")
                    if (descComment.isNotEmpty()) {
                        val padding = maxOf(1, 36 - aliasComment.length - 2)
                        sb.append(" ".repeat(padding))
                    }
                }
                if (descComment.isNotEmpty()) {
                    sb.append(" ; {$descComment}")
                }
                w.write(sb.toString().trimEnd() + "\n")
            }
        }
    }

