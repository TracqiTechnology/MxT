        Triple("gangi", "SelectedGear", "Selected gear"),
        Triple("vfil_w", "VehicleSpeed", "Vehicle speed"),
    )

    private fun formatFactor(f: Double): String {
        if (f == f.toLong().toDouble() && kotlin.math.abs(f) < 1e6) {
            return f.toLong().toString()
        }
        if (kotlin.math.abs(f) >= 0.001) {
            return f.toBigDecimal().stripTrailingZeros().toPlainString()
        }
        return String.format("%.6e", f)
    }
}
